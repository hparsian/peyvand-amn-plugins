    public function calculate( array $answers ): array {
        $answers       = \PsychAssessments\Core\Scoring::sanitize_answers( $answers );
        $stories       = $this->stories();
        $schema_scores = [];
        $max_score     = 0;
        $top_story     = '';

        foreach ( $stories as $key => $story ) {
            $sum = 0;
            foreach ( $story['questions'] as $q ) {
                // clamp صریح: مقیاس 1–9 — اگر پاسخ موجود نباشد مقدار 1 (پایین‌ترین) بازمی‌گردد
                // intval(null)=0 پس ?? 1 کافی نیست؛ clamp حالت edge را پوشش می‌دهد
                $val  = isset( $answers[$q] ) ? max( 1, min( 9, (int) $answers[$q] ) ) : 1;
                $sum += $val;
            }
            $avg = round( $sum / count( $story['questions'] ), 2 );
            $schema_scores[$key] = $avg;
            if ( $avg > $max_score ) {
                $max_score = $avg;
                $top_story = $key;
            }
        }

        arsort( $schema_scores );

        // پرچم‌های بالینی
        $clinical_flags = $this->detect_clinical_flags( $schema_scores );

        return [
            'schema_scores'   => $schema_scores,
            'top_story'       => $top_story,
            // #LS2 fix: از schema_scores[$top_story] خوانده می‌شود نه $max_score
            // در حالت tie، $max_score = آخرین مقدار برابر بود، نه لزوماً قصه غالب
            'top_story_score' => (float) ( $schema_scores[ $top_story ] ?? 0.0 ),
            'clinical_flags'  => $clinical_flags,
        ];
    }

    /**
     * تشخیص الگوهای بالینی مهم بر اساس نمرات
     */
    private function detect_clinical_flags( array $schema_scores ): array {
        $flags = [];
        $threshold_high = 7.0;   // نمره بالای ۷ = فعال
        $threshold_very  = 8.0;  // نمره بالای ۸ = بسیار بالا

        // پرچم قرمز: کنترل‌گری
        if ( ( $schema_scores['police'] ?? 0 ) >= $threshold_high ) {
            $flags[] = [
                'level'   => 'red',
                'story'   => 'police',
                'message' => 'نمره بالای قصه کارآگاه: ارزیابی الگوهای کنترل‌گری و حسادت توصیه می‌شود.',
            ];
        }

        // پرچم قرمز: وحشت / تحمل بدرفتاری
        if ( ( $schema_scores['horror'] ?? 0 ) >= $threshold_high ) {
            $flags[] = [
                'level'   => 'red',
                'story'   => 'horror',
                'message' => 'نمره بالای قصه وحشت: ارزیابی تحمل روابط سمی و اشتباه گرفتن اضطراب با عشق توصیه می‌شود.',
            ];
        }

        // پرچم نارنجی: وابستگی پاتولوژیک
        if ( ( $schema_scores['addiction'] ?? 0 ) >= $threshold_very ) {
            $flags[] = [
                'level'   => 'orange',
                'story'   => 'addiction',
                'message' => 'نمره بسیار بالای قصه اعتیاد: ارزیابی وابستگی و سبک دلبستگی اضطرابی توصیه می‌شود.',
            ];
        }

        // پرچم نارنجی: جنگ + بدون باغبان → تعارض مزمن بدون مراقبت
        if ( ( $schema_scores['war'] ?? 0 ) >= $threshold_high &&
             ( $schema_scores['garden'] ?? 0 ) < 4.0 ) {
            $flags[] = [
                'level'   => 'orange',
                'story'   => 'war',
                'message' => 'ترکیب قصه جنگ بالا + باغبان پایین: الگوی تعارض بدون مراقبت — ارزیابی فرسودگی زوجی توصیه می‌شود.',
            ];
        }

        // پرچم آبی (اطلاع‌رسانی): فداکاری بسیار بالا
        if ( ( $schema_scores['sacrifice'] ?? 0 ) >= $threshold_very ) {
            $flags[] = [
                'level'   => 'blue',
                'story'   => 'sacrifice',
                'message' => 'نمره بسیار بالای قصه فداکاری: بررسی الگوهای مراقبت افراطی و از خودبیگانگی ممکن است مفید باشد.',
            ];
        }

        return $flags;
    }

