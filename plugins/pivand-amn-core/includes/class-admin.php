final class Pas_Core_Admin
{
    private string $page_hook = '';

    private string $health_page_hook = '';
    private string $center_page_hook = '';

    /**
     * نام اکشن nonce که هر افزونه‌ی مصرف‌کننده (quiz-enterprise، case-file)
     * موقع localize کردن جاوااسکریپت خودش با همین رشته‌ی ثابت wp_create_nonce
     * می‌سازد. عمداً یک رشته‌ی ثابت مستند‌شده است، نه یک متد به‌اشتراک‌گذاشته‌شده،
     * تا هیچ افزونه‌ای وابستگی مستقیم به کلاس این افزونه (core) در زمان build
     * نداشته باشد — دقیقاً همان فلسفه‌ی جداسازی که بقیه‌ی قراردادهای فیلتری
     * این اکوسیستم دارند.
     */
    public const LOOKUP_NONCE_ACTION = 'pas_core_lookup_client_name';

    /**
     * اکشن AJAX برای ذخیره‌ی دائمی وضعیت «دیده شد» نوتیس هشدار کلید
     * رمزنگاری. کلاس is-dismissible وردپرس فقط نوتیس را در همان صفحه با
     * جاوااسکریپت محو می‌کند و هیچ درخواستی به سرور نمی‌فرستد؛ بدون این
     * AJAX، نوتیس در هر بارگذاری بعدی صفحه دوباره ظاهر می‌شود چون منبع
     * تصمیم (option) دست‌نخورده می‌ماند.
     */
    public const DISMISS_KEY_NOTICE_ACTION = 'pas_core_dismiss_key_notice';

    public function __construct()
    {
        add_action('admin_menu', [$this, 'register_menu']);
        add_action('admin_notices', [$this, 'maybe_show_key_status_notice']);
        add_action('admin_enqueue_scripts', [$this, 'enqueue_assets']);
        add_action('wp_ajax_' . self::LOOKUP_NONCE_ACTION, [$this, 'ajax_lookup_client_name']);
        add_action('wp_ajax_' . self::DISMISS_KEY_NOTICE_ACTION, [$this, 'ajax_dismiss_key_notice']);
        add_action('admin_post_pas_core_registry_rebuild', [$this, 'handle_registry_rebuild']);
    }

    /**
     * بازسازی دستی رجیستری هویت (فاز ۱). عمداً فقط با کلیک ادمین اجرا می‌شود،
     * نه روی هر بازدید صفحه یا cron: خواندن چند منبع و ساخت ایندکس کاری است
     * که باید قابل‌کنترل و قابل‌زمان‌بندی توسط خود شما بماند.
     */
    public function handle_registry_rebuild(): void
    {
        if (!current_user_can('manage_options')) {
            wp_die('دسترسی غیرمجاز.', 'دسترسی غیرمجاز', ['response' => 403]);
        }

        check_admin_referer('pas_core_registry_rebuild', 'pas_registry_nonce');

        $result = Pas_Core_Client_Registry::rebuild();

        wp_safe_redirect(add_query_arg([
            'page'          => 'pas-core-overview',
            'pas_registry'  => 'done',
            'pas_clients'   => (int) $result['clients'],
            'pas_conflicts' => (int) $result['conflicts'],
            'pas_truncated' => !empty($result['truncated']) ? 1 : 0,
        ], admin_url('admin.php')));
        exit;
    }

    /**
     * نقطه‌ی AJAX مشترک برای همه‌ی فرم‌های «مراجع جدید» در کل اکوسیستم
     * (فعلاً quiz-enterprise و case-file). فقط شماره موبایل می‌گیرد و از
     * زنجیره‌ی فیلتر pas_lookup_known_client_name (پنل مراجعان ← پرونده
     * مراجعین ← آزمون‌ها) نامی که هرجای دیگر قبلاً ثبت شده را برمی‌گرداند —
     * تا درمانگر مجبور نباشد برای یک مراجع تکراری، نام را دوباره تایپ کند.
     * فقط اطلاعاتی؛ چیزی را ذخیره/تغییر نمی‌دهد.
     */
    public function ajax_lookup_client_name(): void
    {
        check_ajax_referer(self::LOOKUP_NONCE_ACTION, 'nonce');

        // این نقطه فقط از دو صفحه‌ی ادمین مصرف می‌شود: quiz-enterprise
        // (نیازمند manage_options) و case-file (نیازمند کپابیلیتی اختصاصی
        // pas_manage_case_files، نه manage_options عمومی — طبق طراحی خودِ
        // آن افزونه برای نقش‌های محدودتر در آینده مثل «منشی»). پس هر دو را
        // قبول می‌کنیم، بدون وابستگی سخت به وجود case-file.
        $allowed = current_user_can('manage_options')
            || (defined('PAS_CF_CAP') && current_user_can(PAS_CF_CAP));

        if (!$allowed) {
            wp_send_json_error(['message' => 'دسترسی غیرمجاز.'], 403);
        }

        $phone = isset($_POST['phone']) ? sanitize_text_field(wp_unslash($_POST['phone'])) : '';

        if ($phone === '') {
            wp_send_json_success(['name' => '']);
        }

        $normalized = class_exists('Pas_Core_Helpers')
            ? Pas_Core_Helpers::normalize_mobile($phone)
            : $phone;

        $name = apply_filters('pas_lookup_known_client_name', '', $normalized);

        wp_send_json_success(['name' => is_string($name) ? $name : '']);
    }

    /**
     * ذخیره‌ی دائمی «دیده شد» برای نوتیس هشدار کلید، وقتی کاربر روی ضربدر
     * نوتیس کلیک می‌کند. فقط زمانی این option ذخیره می‌شود که کلیک واقعاً
     * برای همان مقدار فعلی‌ی pas_core_key_autogenerated_at بوده باشد — اگر
     * بعداً کلید دوباره auto-generate شود (مثلاً بعد از migration هاست) و
     * timestamp عوض شود، نوتیس دوباره نمایش داده می‌شود چون این dismissed
     * قدیمی دیگر با مقدار جدید مطابقت ندارد.
     */
    public function ajax_dismiss_key_notice(): void
    {
        check_ajax_referer(self::DISMISS_KEY_NOTICE_ACTION, 'nonce');

        if (!current_user_can('manage_options')) {
            wp_send_json_error(['message' => 'دسترسی غیرمجاز.'], 403);
        }

        $autogen_at = get_option('pas_core_key_autogenerated_at');
        update_option('pas_core_key_notice_dismissed_for', $autogen_at, false);

        wp_send_json_success();
    }

    public function enqueue_assets(string $hook): void
    {
        // نوتیس هشدار کلید در admin_notices عمومی است و در همه‌ی صفحات
        // ادمین (نه فقط صفحه‌ی خود این افزونه) نمایش داده می‌شود، پس اسکریپت
        // dismiss باید همه‌جا لود شود، نه فقط پشت شرط $this->page_hook.
        if (get_option('pas_core_key_autogenerated_at')) {
            wp_enqueue_script(
                'pas-core-dismiss-key-notice',
                PAS_CORE_URL . 'assets/js/dismiss-key-notice.js',
                [],
                PAS_CORE_VERSION,
                true
            );
            wp_localize_script('pas-core-dismiss-key-notice', 'PasCoreDismissKeyNotice', [
                'ajaxUrl' => admin_url('admin-ajax.php'),
                'action'  => self::DISMISS_KEY_NOTICE_ACTION,
                'nonce'   => wp_create_nonce(self::DISMISS_KEY_NOTICE_ACTION),
            ]);
        }

        if ($hook === $this->center_page_hook) {
            wp_enqueue_style(
                'pas-core-admin',
                PAS_CORE_URL . 'assets/css/admin.css',
                [ \Pas_Core_Tokens::handle() ],
                PAS_CORE_VERSION
            );
            wp_enqueue_style('pas-core-center', PAS_CORE_URL . 'assets/css/center.css', ['pas-core-admin'], PAS_CORE_VERSION);

            // ApexCharts سلف‌هاست — فقط در همین صفحه، بدون هیچ CDN.
            wp_enqueue_script(
                'pas-core-apexcharts',
                PAS_CORE_URL . 'assets/vendor/apexcharts/apexcharts.min.js',
                [],
                '3.54.1',
                true
            );
            wp_enqueue_script(
                'pas-core-center-chart',
                PAS_CORE_URL . 'assets/js/center.js',
                ['pas-core-apexcharts'],
                PAS_CORE_VERSION,
                true
            );

            return;
        }

        if ($hook !== $this->page_hook && $hook !== $this->health_page_hook) {
            return;
        }

        wp_enqueue_style(
            'pas-core-admin',
            PAS_CORE_URL . 'assets/css/admin.css',
            [ \Pas_Core_Tokens::handle() ],
            PAS_CORE_VERSION
        );
    }

    public function maybe_show_key_status_notice(): void
    {
        if (!current_user_can('manage_options')) {
            return;
        }

        $autogen_at = get_option('pas_core_key_autogenerated_at');
        $dismissed_for = get_option('pas_core_key_notice_dismissed_for');

        // اگر برای همین مقدار autogen_at قبلاً dismiss ثبت شده، نشون نده.
        // اگر کلید دوباره ساخته شد (autogen_at عوض شد)، dismissed قدیمی
        // دیگر معتبر نیست و نوتیس دوباره ظاهر می‌شود.
        if ($autogen_at && $dismissed_for !== $autogen_at) {
            printf(
                '<div id="pas-core-key-notice" class="notice notice-warning is-dismissible"><p><strong>پیوند امن:</strong> کلید رمزنگاری خودکار ساخته و در <code>wp-content/pas-encryption-key.php</code> ذخیره شد (زمان: %s). یک نسخه از این فایل را همین حالا جای امنی (پسورد منیجر) هم نگه دار — اگر این فایل از سرور گم شود، داده‌های رمزنگاری‌شده برای همیشه غیرقابل‌بازیابی می‌شوند.</p></div>',
                esc_html($autogen_at)
            );
        }

        if (get_option('pas_core_key_autogen_failed') === '1' && !Pas_Core_Crypto::is_configured()) {
            $suggested = Pas_Core_Crypto::generate_suggested_key();
            ?>
            <div class="notice notice-error">
                <p><strong>پیوند امن:</strong> نتونستیم کلید رمزنگاری رو خودکار بسازیم (احتمالاً پوشه‌ی wp-content روی این هاست قابل‌نوشتن نیست). باید دستی تنظیمش کنی — یکی از این دو راه:</p>
                <p>۱. این خط رو به <code>wp-config.php</code> اضافه کن: <code style="user-select:all;">define('PAS_CORE_ENCRYPTION_KEY', '<?php echo esc_html($suggested); ?>');</code></p>
                <p>۲. یا یه فایل به اسم <code>pas-encryption-key.php</code> با محتوای <code>&lt;?php return '<?php echo esc_html($suggested); ?>';</code> بساز و با FTP توی <code>wp-content/</code> آپلودش کن.</p>
            </div>
            <?php
        }
    }

    public function register_menu(): void
    {
        $this->page_hook = add_menu_page(
            'زیرساخت پیوند امن',
            'زیرساخت پیوند امن',
            'manage_options',
            'pas-core-overview',
            [$this, 'render_page'],
            'dashicons-networking',
            2
        );

        // فاز ۱۲ / گام ۵: مرکز مدیریت — صفحهٔ اول این منو.
        $this->center_page_hook = add_submenu_page(
            'pas-core-overview',
            'مرکز مدیریت',
            'مرکز مدیریت',
            'manage_options',
            'pas-core-center',
            ['Pas_Core_Center', 'render']
        );

        // فاز ۱۰: نمای واحد سلامت اکوسیستم (فقط‌خواندنی).
        $this->health_page_hook = add_submenu_page(
            'pas-core-overview',
            'سلامت اکوسیستم',
            'سلامت اکوسیستم',
            'manage_options',
            'pas-core-health',
            [$this, 'render_health_page']
        );
    }

